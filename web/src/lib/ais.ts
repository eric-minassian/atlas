/** The flag state an MMSI implies, for ship stations (and craft associated with one). */
export const flagOf = (mmsi: number): string | undefined => {
  const digits = String(mmsi).padStart(9, '0');
  if (digits.length !== 9) return undefined;
  const mid = digits.startsWith('98')
    ? digits.slice(2, 5)
    : /^[2-7]/.test(digits)
      ? digits.slice(0, 3)
      : undefined;
  return mid === undefined ? undefined : countryByMid.get(Number(mid));
};
