export const shipTypeLabel = (type: number): string | undefined => {
  if (type <= 0 || type >= 100) return undefined;
  const special = specialTypes[type];
  if (special) return special;
  const decade = Math.floor(type / 10);
  return (
    {
      2: 'Wing in ground',
      4: 'High-speed craft',
      6: 'Passenger',
      7: 'Cargo',
      8: 'Tanker',
      9: 'Other',
    } as Readonly<Record<number, string>>
  )[decade];
};

