/** What AIS codes mean: ship types, navigational status, and the flag an MMSI implies. */

export type ShipCategory = 'cargo' | 'tanker' | 'passenger' | 'fishing' | 'pleasure' | 'other';

/** The broad class of an AIS ship and cargo type (ITU-R M.1371, table 53). */
export const shipCategoryOf = (type: number): ShipCategory => {
  if (type >= 70 && type < 80) return 'cargo';
  if (type >= 80 && type < 90) return 'tanker';
  // High-speed craft are mostly fast ferries.
  if ((type >= 60 && type < 70) || (type >= 40 && type < 50)) return 'passenger';
  if (type === 30) return 'fishing';
  if (type === 36 || type === 37) return 'pleasure';
  return 'other';
};

